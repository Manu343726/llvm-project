/// CucarachaDAGToDAGISel - Cucaracha specific code to select Cucaracha machine
/// instructions for SelectionDAG operations.
///
namespace {
class CucarachaDAGToDAGISel : public SelectionDAGISel {
  const CucarachaSubtarget &Subtarget;
  static char ID;

public:
  explicit CucarachaDAGToDAGISel(CucarachaTargetMachine &TM,
                                 CodeGenOpt::Level OptLevel)
      : SelectionDAGISel(ID, TM, OptLevel), Subtarget(*TM.getSubtargetImpl()) {}

  void Select(SDNode *N) override;

  void SelectFrameIndex(SDNode *N);
  bool SelectAddr(SDValue Addr, SDValue &Base, SDValue &Offset);

  virtual StringRef getPassName() const override {
    return "Cucaracha DAG->DAG Pattern Instruction Selection";
  }

private:
  void SelectMoveImmediate(SDNode *N);
  void SelectConditionalBranch(SDNode *N);

// Include the pieces autogenerated from the target description.
#include "CucarachaGenDAGISel.inc"
};

char CucarachaDAGToDAGISel::ID = 0;

} // end anonymous namespace

bool CucarachaDAGToDAGISel::SelectAddr(SDValue Addr, SDValue &Base,
                                       SDValue &Offset) {
  if (FrameIndexSDNode *FIN = dyn_cast<FrameIndexSDNode>(Addr)) {
    EVT PtrVT = getTargetLowering()->getPointerTy(CurDAG->getDataLayout());
    Base = CurDAG->getTargetFrameIndex(FIN->getIndex(), PtrVT);
    Offset = CurDAG->getTargetConstant(0, Addr, MVT::i32);
    return true;
  }
  if (Addr.getOpcode() == ISD::TargetExternalSymbol ||
      Addr.getOpcode() == ISD::TargetGlobalAddress ||
      Addr.getOpcode() == ISD::TargetGlobalTLSAddress) {
    return false; // direct calls.
  }

  Base = Addr;
  Offset = CurDAG->getTargetConstant(0, Addr, MVT::i32);
  return true;
}

void CucarachaDAGToDAGISel::SelectMoveImmediate(SDNode *N) {
  // Make sure the immediate size is supported.
  ConstantSDNode *ConstVal = cast<ConstantSDNode>(N);
  uint64_t ImmVal = ConstVal->getZExtValue();
  uint64_t SupportedMask = 0xfffffffff;
  if ((ImmVal & SupportedMask) != ImmVal) {
    return SelectCode(N);
  }

  // Select the low part of the immediate move.
  uint64_t LoMask = 0xffff;
  uint64_t HiMask = 0xffff0000;
  uint64_t ImmLo = (ImmVal & LoMask);
  uint64_t ImmHi = (ImmVal & HiMask);
  SDValue ConstLo = CurDAG->getTargetConstant(ImmLo, N, MVT::i32);
  SDNode *Move =
      CurDAG->SelectNodeTo(N, Cucaracha::MOVLOi16, MVT::i32, ConstLo);

  // Select the low part of the immediate move, if needed.
  if (ImmHi) {
    SDValue ConstHi = CurDAG->getTargetConstant(ImmHi >> 16, N, MVT::i32);
    CurDAG->SelectNodeTo(N, Cucaracha::MOVHIi16, MVT::i32, SDValue(Move, 0),
                         ConstHi);
  }
}

void CucarachaDAGToDAGISel::SelectConditionalBranch(SDNode *N) {
  SDValue Chain = N->getOperand(0);
  SDValue Cond = N->getOperand(1);
  SDValue LHS = N->getOperand(2);
  SDValue RHS = N->getOperand(3);
  SDValue Target = N->getOperand(4);

  // Generate a comparison instruction.
  EVT CompareTys[] = {MVT::Other, MVT::Glue};
  SDVTList CompareVT = CurDAG->getVTList(CompareTys);
  SDValue CompareOps[] = {LHS, RHS, Chain};
  SDNode *Compare =
      CurDAG->getMachineNode(Cucaracha::CMP, N, CompareVT, CompareOps);

  // Generate a predicated branch instruction.
  CondCodeSDNode *CC = cast<CondCodeSDNode>(Cond.getNode());
  SDValue CCVal = CurDAG->getTargetConstant(CC->get(), N, MVT::i32);
  SDValue BranchOps[] = {CCVal, Target, SDValue(Compare, 0),
                         SDValue(Compare, 1)};
  CurDAG->SelectNodeTo(N, Cucaracha::Bcc, MVT::Other, BranchOps);
}

void CucarachaDAGToDAGISel::SelectFrameIndex(SDNode *N) {
  FrameIndexSDNode *FIN = dyn_cast<FrameIndexSDNode>(N);
  EVT PtrVT = getTargetLowering()->getPointerTy(CurDAG->getDataLayout());
  const auto Address = CurDAG->getTargetFrameIndex(FIN->getIndex(), PtrVT);
  auto *const Mov =
      CurDAG->getMachineNode(Cucaracha::MOVi32, N, MVT::i32, Address);
  CurDAG->ReplaceAllUsesWith(N, Mov);
}

void CucarachaDAGToDAGISel::Select(SDNode *N) {
  if (N->isMachineOpcode()) {
    N->setNodeId(-1);
    return; // Already selected.
  }

  switch (N->getOpcode()) {
  case ISD::Constant:
    return SelectMoveImmediate(N);
  case ISD::BR_CC:
    return SelectConditionalBranch(N);
  case ISD::FrameIndex:
    return SelectFrameIndex(N);
  }

  return SelectCode(N);
}

/// createCucarachaISelDag - This pass converts a legalized DAG into a
/// Cucaracha-specific DAG, ready for instruction scheduling.
///
FunctionPass *llvm::createCucarachaISelDag(CucarachaTargetMachine &TM,
                                           CodeGenOpt::Level OptLevel) {
  return new CucarachaDAGToDAGISel(TM, OptLevel);
}
