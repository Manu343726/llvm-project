#ifndef LLVM_LIB_TARGET_Cucaracha_CucarachaSUBTARGET_H
#define LLVM_LIB_TARGET_Cucaracha_CucarachaSUBTARGET_H

#include "CucarachaFrameLowering.h"
#include "CucarachaISelLowering.h"
#include "CucarachaInstrInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/TargetParser/Triple.h"
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "CucarachaGenSubtargetInfo.inc"

namespace llvm {
class StringRef;

class CucarachaSubtarget : public CucarachaGenSubtargetInfo {
  Triple TargetTriple;
  virtual void anchor();

  bool Is64Bit;

#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER)                    \
  bool ATTRIBUTE = DEFAULT;
#include "CucarachaGenSubtargetInfo.inc"

  CucarachaInstrInfo InstrInfo;
  CucarachaTargetLowering TLInfo;
  SelectionDAGTargetInfo TSInfo;
  CucarachaFrameLowering FrameLowering;

public:
  CucarachaSubtarget(const Triple &TT, const std::string &CPU,
                     const std::string &FS, const TargetMachine &TM,
                     bool is64bit);

  const CucarachaInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const CucarachaRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const CucarachaTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

  bool enableMachineScheduler() const override;

#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER)                    \
  bool GETTER() const { return ATTRIBUTE; }
#include "CucarachaGenSubtargetInfo.inc"

  /// ParseSubtargetFeatures - Parses features string setting specified
  /// subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);
  CucarachaSubtarget &initializeSubtargetDependencies(StringRef CPU,
                                                      StringRef FS);

  bool is64Bit() const { return Is64Bit; }

  /// The 64-bit ABI uses biased stack and frame pointers, so the stack frame
  /// of the current function is the area from [%sp+BIAS] to [%fp+BIAS].
  int64_t getStackPointerBias() const { return is64Bit() ? 2047 : 0; }

  /// Given a actual stack size as determined by FrameInfo, this function
  /// returns adjusted framesize which includes space for register window
  /// spills and arguments.
  int getAdjustedFrameSize(int stackSize) const;

  bool isTargetLinux() const { return TargetTriple.isOSLinux(); }
};

} // end namespace llvm

#endif
